@slaves_api.route('/tokens', methods=['POST'])
@token_required
@admin_required
def generate_token(current_user):
    """Generate a new integration token"""
    data = request.get_json() or {}
    expiry_minutes = data.get('expiry_minutes',
        current_app.config.get('SLAVE_TOKEN_EXPIRY_MINUTES', 60))

    # Limit expiry to max 24 hours (1440 minutes)
    expiry_minutes = min(expiry_minutes, 1440)

    token = SlaveToken.generate(
        user_id=current_user.id,
        expiry_minutes=expiry_minutes
    )

    audit_log(
        'slave_token_generated',
        'slave_token',
        token.token[:8],
        new_value={'expiry_minutes': expiry_minutes},
        user=current_user
    )

    # Build the installation command
    master_url = request.host_url.rstrip('/')
    install_command = f"curl -sSL {master_url}/install-slave.sh | sudo bash -s -- --master={request.host.split(':')[0]} --token={token.token}"

    return jsonify({
        'token': token.to_dict(),
        'install_command': install_command
    })


@slaves_api.route('/tokens/<int:token_id>', methods=['DELETE'])
@token_required
@admin_required
def revoke_token(current_user, token_id):
    """Revoke an integration token"""
    token = SlaveToken.query.get(token_id)

    if not token:
        return jsonify({'error': 'Token not found'}), 404

    from models import db
    db.session.delete(token)
    db.session.commit()

    audit_log(
        'slave_token_revoked',
        'slave_token',
        token.token[:8],
        user=current_user
    )

    return jsonify({'message': 'Token revoked'})


