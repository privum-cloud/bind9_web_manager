@slaves_api.route('/<int:slave_id>', methods=['DELETE'])
@token_required
@admin_required
def delete_slave(current_user, slave_id):
    """Remove a slave"""
    slave = Slave.query.get(slave_id)

    if not slave:
        return jsonify({'error': 'Slave not found'}), 404

    ip_address = slave.ip_address
    slave.delete()

    # Update BIND configuration
    update_bind_allow_transfer()

    audit_log(
        'slave_deleted',
        'slave',
        ip_address,
        user=current_user
    )

    return jsonify({'message': 'Slave removed successfully'})


@slaves_api.route('/<int:slave_id>/status', methods=['PUT'])
@token_required
@admin_required
def update_slave_status(current_user, slave_id):
    """Update slave status"""
    slave = Slave.query.get(slave_id)

    if not slave:
        return jsonify({'error': 'Slave not found'}), 404

    data = request.get_json()
    new_status = data.get('status')

    if new_status not in ['active', 'inactive', 'pending', 'error']:
        return jsonify({'error': 'Invalid status'}), 400

    old_status = slave.status
    slave.set_status(new_status)

    # Update BIND if status changed to/from active
    if (old_status == 'active') != (new_status == 'active'):
        update_bind_allow_transfer()

    audit_log(
        'slave_status_changed',
        'slave',
        slave.ip_address,
        old_value={'status': old_status},
        new_value={'status': new_status},
        user=current_user
    )

    return jsonify(slave.to_dict())


