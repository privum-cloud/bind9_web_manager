@slaves_api.route('/zones', methods=['GET'])
def get_zones_for_sync():
    """
    Get list of zones for slave synchronization.
    Public endpoint - only returns zone names and types.
    Used by slave sync script.
    """
    from services.dns_service import DNSService
    dns = DNSService()
    zones = dns.list_zones()

    # Only return master zones (slaves should sync these)
    master_zones = [
        {'name': z['name'], 'type': z.get('type', 'master'), 'file': z.get('file', f"db.{z['name']}")}
        for z in zones if z.get('type', 'master') == 'master'
    ]

    return jsonify({
        'zones': master_zones,
        'total': len(master_zones)
    })


@slaves_api.route('/config', methods=['GET'])
def get_slave_config():
    """
    Get configuration for slave installation.
    Requires valid integration token.
    Called by install-slave.sh script.
    """
    token_value = request.args.get('token')

    if not token_value:
        return jsonify({'error': 'Token required'}), 401

    # Validate token
    token = SlaveToken.get_by_token(token_value)

    if not token:
        return jsonify({'error': 'Invalid token'}), 401

    if not token.is_valid():
        return jsonify({'error': 'Token expired or already used'}), 401

    # Get RNDC key content
    rndc_key_path = current_app.config.get('RNDC_KEY_PATH', '/etc/bind/rndc.key')
    rndc_key_content = ''

    try:
        if os.path.exists(rndc_key_path):
            with open(rndc_key_path, 'r') as f:
                rndc_key_content = f.read()
    except Exception as e:
        current_app.logger.error(f"Error reading RNDC key: {e}")
        return jsonify({'error': 'Could not read RNDC key'}), 500

    # Get list of zones for slave configuration
    from services.dns_service import DNSService
    dns = DNSService()
    zones = dns.list_zones()

    # Get master IP (for slave configuration)
    master_ip = request.host.split(':')[0]  # Get hostname/IP from request

    # Read shared slave-agent token so the slave can authenticate push
    # requests from the master (and vice-versa). Generated by install.sh
    # on master install; same secret across all slaves.
    agent_token = ''
    agent_token_path = current_app.config.get(
        'SLAVE_AGENT_TOKEN_PATH', '/opt/dns-manager/slave-agent.token'
    )
    try:
        if os.path.exists(agent_token_path):
            with open(agent_token_path, 'r') as f:
                agent_token = f.read().strip()
    except Exception as e:
        current_app.logger.warning(f"Could not read slave-agent token: {e}")

    # Return configuration
    return jsonify({
        'rndc_key': rndc_key_content,
        'master_ip': master_ip,
        'zones': [{'name': z['name'], 'file': z['file']} for z in zones],
        'bind_config_dir': current_app.config.get('BIND_CONFIG_DIR', '/etc/bind'),
        'zones_path': current_app.config.get('ZONES_PATH', '/var/lib/bind/zones'),
        'slave_agent_token': agent_token,
    })


@slaves_api.route('/register', methods=['POST'])
def register_slave():
    """
    Register a new slave server.
    Called by install-slave.sh after successful configuration.
    """
    data = request.get_json()

    if not data:
        return jsonify({'error': 'No data provided'}), 400

    token_value = data.get('token')
    slave_ip = data.get('ip_address') or request.remote_addr
    hostname = data.get('hostname')

    if not token_value:
        return jsonify({'error': 'Token required'}), 401

    # Validate token
    token = SlaveToken.get_by_token(token_value)

    if not token:
        return jsonify({'error': 'Invalid token'}), 401

    if not token.is_valid():
        return jsonify({'error': 'Token expired or already used'}), 401

    # Check if slave already exists
    existing = Slave.get_by_ip(slave_ip)
    if existing:
        # Update existing slave
        existing.hostname = hostname
        existing.set_status('active')
        existing.update_last_seen()
        slave = existing
    else:
        # Create new slave
        slave = Slave.create(
            ip_address=slave_ip,
            hostname=hostname,
            notes=f'Registered via token {token.token[:8]}...'
        )

    # Mark token as used
    token.mark_used(slave_ip)

    # Update BIND configuration to allow transfer to this slave
    update_result = update_bind_allow_transfer()

    audit_log(
        'slave_registered',
        'slave',
        slave_ip,
        new_value={'hostname': hostname, 'token_id': token.id}
    )

    return jsonify({
        'message': 'Slave registered successfully',
        'slave': slave.to_dict(),
        'bind_updated': update_result
    })


@slaves_api.route('/heartbeat', methods=['POST'])
def slave_heartbeat():
    """
    Heartbeat endpoint for slaves to report status.
    """
    data = request.get_json() or {}
    slave_ip = data.get('ip_address') or request.remote_addr

    slave = Slave.get_by_ip(slave_ip)

    if not slave:
        return jsonify({'error': 'Slave not registered'}), 404

    slave.update_last_seen()

    # Update sync time if provided
    if data.get('last_sync'):
        slave.update_last_sync()

    return jsonify({
        'status': 'ok',
        'slave': slave.to_dict()
    })


