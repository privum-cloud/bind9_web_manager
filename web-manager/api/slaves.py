def update_bind_allow_transfer():
    """
    Update BIND configuration to allow zone transfers to active slaves.
    Returns True if successful, error message otherwise.
    """
    try:
        # Get all active slave IPs
        active_slaves = Slave.get_active()
        slave_ips = [s.ip_address for s in active_slaves]

        if not slave_ips:
            slave_ips = ['none']

        # Read current named.conf.local
        named_conf_local = current_app.config.get('NAMED_CONF_LOCAL')

        if not os.path.exists(named_conf_local):
            return "Named config not found"

        with open(named_conf_local, 'r') as f:
            content = f.read()

        # Update or add slaves ACL
        slaves_acl = 'acl "slaves" {\n'
        for ip in slave_ips:
            if ip != 'none':
                slaves_acl += f'    {ip};\n'
        slaves_acl += '};\n'

        # Check if ACL exists
        acl_pattern = r'acl\s+"slaves"\s*\{[^}]*\};'

        if re.search(acl_pattern, content):
            # Update existing ACL
            content = re.sub(acl_pattern, slaves_acl.strip(), content)
        else:
            # Add ACL at the beginning
            content = slaves_acl + '\n' + content

        # Update allow-transfer in zone blocks
        # Pattern: allow-transfer { ... };
        transfer_pattern = r'allow-transfer\s*\{[^}]*\}'

        if slave_ips and slave_ips[0] != 'none':
            new_transfer = 'allow-transfer { slaves; }'
        else:
            new_transfer = 'allow-transfer { none; }'

        content = re.sub(transfer_pattern, new_transfer, content)

        # Write updated config
        with open(named_conf_local, 'w') as f:
            f.write(content)

        # Reload BIND
        from services.dns_service import DNSService
        dns = DNSService()
        success, msg = dns.reload_all()

        if success:
            return True
        else:
            return f"Config updated but reload failed: {msg}"

    except Exception as e:
        current_app.logger.error(f"Error updating BIND config: {e}")
        return str(e)


def check_slave_connectivity(ip_address):
    """
    Check if we can connect to a slave's DNS port.
    """
    try:
        result = subprocess.run(
            ['dig', '+short', '+time=2', f'@{ip_address}', 'version.bind', 'chaos', 'txt'],
            capture_output=True,
            text=True,
            timeout=5
        )
        return result.returncode == 0
    except Exception:
        return False
